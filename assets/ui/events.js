    function dispatch(event) {
        const attr = 'data-spark-on' + event.type;
        let node = event.target?.nodeType === 1 ? event.target : event.target?.parentElement;
        while (node && node !== document) {
            const id = node.getAttribute?.(attr);
            if (id && Object.prototype.hasOwnProperty.call(handlers, id)) {
                const result = handlers[id].call(node, event);
                if (result === false) event.preventDefault();
                if (event.cancelBubble) { event.stopImmediatePropagation(); break; }
            }
            // load/error do not bubble: their handler belongs to the target only.
            if (event.type === 'error' || event.type === 'load') break;
            node = node.parentElement;
        }
    }
